function tarik(){
  const pool = KARTU[jenis].filter(t => t !== terakhir);
  terakhir = pool[Math.floor(Math.random() * pool.length)];
  $('cardText').textContent = terakhir;
}
function ayun(){
  $('hang').classList.remove('again');
  void $('hang').offsetWidth;
  $('hang').classList.add('again');
}
function balik(jadiKartu){
  if(jadiKartu) tarik();
  $('flip').classList.toggle('turned', jadiKartu);
  $('front').inert = jadiKartu;
  $('back').inert = !jadiKartu;
  ayun();
  (jadiKartu ? $('draw') : $('knock')).focus({preventScroll:true});
}
$('front').onclick = () => balik(true);
$('unflip').onclick = () => balik(false);
$('draw').onclick = () => { tarik(); ayun(); };
document.querySelectorAll('.tick').forEach(t => t.onclick = () => {
  document.querySelectorAll('.tick').forEach(x => x.setAttribute('aria-pressed', x === t));
  jenis = t.dataset.mode;
  tarik();
});

document.querySelectorAll('.row').forEach(row => row.onclick = () => {
  document.querySelectorAll('.row').forEach(r => r.setAttribute('aria-pressed', r === row));
  const [teks, mode, kode] = PESANAN[row.dataset.mode];
  $('slipText').textContent = teks;
  $('slipMode').textContent = mode;
  $('slipGo').href = $('slipGo').dataset.base + '?mode=' + kode;
});

